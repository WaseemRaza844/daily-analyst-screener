"use strict";
(() => {
  function init() {
    const get=id=>document.getElementById(id);
    const panel=get("research-chat"),launch=get("research-launch"),close=get("research-close"),form=get("research-form"),input=get("research-question"),messages=get("research-messages"),send=get("research-send");
    if (![panel,launch,close,form,input,messages,send].every(Boolean)) { console.error("Chat UI missing required elements"); return; }
    const asNumber=v=>v===null||v===undefined||v===""||!Number.isFinite(Number(v))?null:Number(v);
    const fmt=(v,d=2)=>asNumber(v)===null?"N/A":Number(v).toLocaleString("en-US",{maximumFractionDigits:d});
    const say=(who,message)=>{const el=document.createElement("div");el.className="research-message "+who;el.textContent=message;messages.appendChild(el);messages.scrollTop=messages.scrollHeight;};
    launch.onclick=()=>{panel.hidden=!panel.hidden;launch.setAttribute("aria-expanded",String(!panel.hidden));if(!panel.hidden)input.focus();};
    close.onclick=()=>{panel.hidden=true;launch.setAttribute("aria-expanded","false");launch.focus();};
    document.addEventListener("keydown",e=>{if(e.key==="Escape"&&!panel.hidden)close.click();});
    const dictionary={"p/e":"P/E is the share price divided by earnings per share. It is not meaningful when earnings are negative.","forward p/e":"Forward P/E uses projected earnings, which may be inaccurate.","peg":"PEG adjusts the P/E ratio for expected earnings growth. Missing or negative earnings make it unreliable.","eps":"EPS is earnings per share, which can be positive or negative.","free cash flow":"Free cash flow is cash generated by operations after capital expenditures.","debt":"Debt-to-equity compares borrowings with shareholders' equity.","roe":"Return on equity compares net income with shareholder equity."};
    const base=new URL("./",document.currentScript?.src||location.href);
    const apiUrl=(window.STOCK_RESEARCH_API_URL || "https://daily-stock-research-api.waseemraza844.workers.dev").trim(); // configured in chat-config.js; never put a provider key here.
    async function snapshot(symbol){
      const day=get("day")?.value;
      if(day){try{const r=await fetch(new URL("docs/history/"+encodeURIComponent(day)+".json",base),{cache:"no-store"});if(r.ok){const data=await r.json();const match=(data.matches||[]).find(x=>x.ticker===symbol);if(match)return {...match,date:data.generated_utc,source:"saved dashboard"};}}catch(e){}}
      try{const r=await fetch(new URL("docs/research/"+symbol+".json",base),{cache:"no-store"});if(r.ok)return {...await r.json(),source:"research watchlist"};}catch(e){}
      return null;
    }
    function summary(x){
      const v=x.indicators||{};
      const targetDelta=asNumber(x.price)&&asNumber(x.target)?((x.target/x.price-1)*100).toFixed(1)+"%":"N/A";
      return (x.name||x.ticker)+" ("+x.ticker+") — saved source: "+x.source+". Price: $"+fmt(x.price)+"; analyst consensus: "+(x.rating||"N/A")+"; analyst target: $"+fmt(x.target)+" (difference "+targetDelta+"). Revenue growth: "+(asNumber(x.growth)===null?"N/A":fmt(x.growth*100)+"%")+". P/E: "+fmt(v.pe)+"; forward P/E: "+fmt(v.forward_pe)+"; PEG: "+fmt(v.peg)+"; EPS: "+fmt(v.eps)+". Free cash flow: "+(Array.isArray(x.fcf)?x.fcf.slice(0,2).map(v=>fmt(v,0)).join(" vs. "):"N/A")+". This is dated research, not a personal Buy/Sell recommendation.";
    }
    const companySymbols = {
      "NVIDIA":"NVDA", "APPLE":"AAPL", "MICROSOFT":"MSFT",
      "AMAZON":"AMZN", "ALPHABET":"GOOGL", "GOOGLE":"GOOGL",
      "TESLA":"TSLA", "META":"META", "COREWEAVE":"CRWV",
      "AMD":"AMD", "PALANTIR":"PLTR", "COINBASE":"COIN",
      "NETFLIX":"NFLX", "NU HOLDINGS":"NU"
    };
    const stopwords = new Set(["THE","THIS","THAT","FOR","ABOUT","NOW","WAIT","BUY","SELL","STOCK","STOCKS","SHOULD","PLEASE","ANALYZE","ANALYSIS","WHAT","WHEN","WHY","CAN","YOU","IS","IT","MY","ME","I","A","AN"]);
    function extract(question){
      const original=question.trim();
      const upper=original.toUpperCase();
      for(const [name,symbol] of Object.entries(companySymbols)){
        if(new RegExp("\\b"+name.replace(/ /g,"\\s+")+"\\b").test(upper)) return symbol;
      }
      const explicit=upper.match(/\$([A-Z]{1,6})\b/);
      if(explicit&&!stopwords.has(explicit[1]))return explicit[1];
      const direct=upper.match(/^\$?([A-Z]{1,6})$/);
      if(direct&&!stopwords.has(direct[1]))return direct[1];
      const named=upper.match(/\b(?:TICKER|SYMBOL|ANALYZE|ANALYSE)\s+\$?([A-Z]{1,6})\b/);
      if(named&&!stopwords.has(named[1]))return named[1];
      const known=Array.from(document.querySelectorAll(".stock summary")).map(x=>x.textContent.split(" ")[0].toUpperCase()).filter(Boolean);
      for(const ticker of known){if(new RegExp("\\b"+ticker+"\\b").test(upper))return ticker;}
      const candidates=original.match(/\b[A-Z]{2,6}\b/g)||[];
      return candidates.find(x=>!stopwords.has(x))||null;
    }
    async function ask(q){
      say("user",q);send.disabled=true;
      try{
        const symbol=extract(q);
        if(symbol){
          let data=null, liveError=null;
          if(apiUrl){
            try {
              const endpoint=apiUrl.endsWith("/")?apiUrl.slice(0,-1):apiUrl;
              const response=await fetch(endpoint+"/stock?ticker="+encodeURIComponent(symbol),{cache:"no-store"});
              const body=await response.json();
              if(!response.ok)throw Error(body.error||"Data provider unavailable");
              data={...body,source:"live research API"};
            } catch(err){liveError=err.message||String(err);}
          }
          if(!data)data=await snapshot(symbol);
          if(data){
            say("assistant",summary(data)+(liveError?"\n\nLive lookup failed ("+liveError+"); showing a saved snapshot instead.":""));
          } else {
            say("assistant","Live data unavailable for "+symbol+(liveError?": "+liveError:"")+". Verify independently at https://finance.yahoo.com/quote/"+symbol+"/");
          }
        } else {
          const key=Object.keys(dictionary).find(k=>q.toLowerCase().includes(k));
          say("assistant",key?dictionary[key]:"Try 'Analyze CRWV', 'Analyze NU', 'Explain forward P/E', or 'What is PEG?'. The assistant explains verified numbers and flags unavailable information.");
        }
      }catch(error){say("assistant","Could not retrieve ticker data: "+error.message);}finally{send.disabled=false;}
    }
    form.addEventListener("submit",e=>{e.preventDefault();const q=input.value.trim();if(q){input.value="";ask(q);}});
    document.querySelectorAll("[data-question]").forEach(b=>b.addEventListener("click",()=>ask(b.dataset.question)));
    const ai=get("research-enable-ai");if(ai){ai.hidden=true;}
    say("assistant","Chat ready. Ask about a ticker or a financial indicator. Dated dashboard metrics are available now; arbitrary ticker lookup requires connecting the free backend.");
  }
  if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",init,{once:true});else init();
})();
